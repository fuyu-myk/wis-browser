//! Whether a captured login is offered: new, or a new password for one saved.

use zeroize::Zeroizing;

use crate::state::AppState;

/// What is known about a captured login.
pub(super) struct Login {
    /// A login is saved under this username for the host.
    pub saved: bool,
    /// The password is one Wis generated.
    pub generated: bool,
    /// The page was a change-password form.
    pub changed: bool,
    /// Whether the saved password differs, known only while the vault is open.
    pub differs: Option<bool>,
}

/// Whether a captured login is offered for saving. One already saved under
/// that username is skipped, unless its password is new: generated by Wis,
/// set on a change-password form, or seen to differ with the vault open.
pub(super) fn should_offer(login: Login) -> bool {
    !login.saved
        || login.generated
        || (login.changed && login.differs != Some(false))
        || login.differs == Some(true)
}

/// The saved login a capture would update.
pub(super) fn target(
    existing: Vec<wis_storage::CredentialRecord>,
    username: &str,
    changed: bool,
) -> Option<wis_storage::CredentialRecord> {
    if let Some(i) = existing.iter().position(|c| c.username == username) {
        return existing.into_iter().nth(i);
    }
    match <[_; 1]>::try_from(existing) {
        Ok([only]) if changed => Some(only),
        _ => None,
    }
}

/// Whether `record`'s saved password differs from `password`, or `None` while
/// the vault is locked or the record can't be opened.
pub(super) async fn differs_from(
    state: &AppState,
    record: wis_storage::CredentialRecord,
    password: &str,
) -> Option<bool> {
    let guard = state.vault_key.lock().await;
    let key = guard.as_ref()?;
    let blob = wis_secrets::EncryptedBlob {
        ciphertext: record.ciphertext,
        nonce: record.nonce,
    };
    let plaintext = Zeroizing::new(wis_secrets::decrypt(key, &blob).ok()?);
    Some(plaintext.as_slice() != password.as_bytes())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn login(saved: bool) -> Login {
        Login {
            saved,
            generated: false,
            changed: false,
            differs: None,
        }
    }

    #[test]
    fn a_new_login_is_offered() {
        assert!(should_offer(login(false)));
    }

    #[test]
    fn a_login_already_saved_is_not_offered_again() {
        assert!(!should_offer(login(true)));
        assert!(!should_offer(Login {
            differs: Some(false),
            ..login(true)
        }));
    }

    /// A password Wis generated is new by construction, so a saved username
    /// means a password change. Skipping it would keep the old password
    /// saved and the new one nowhere.
    #[test]
    fn a_generated_password_is_offered_even_over_a_saved_login() {
        assert!(should_offer(Login {
            generated: true,
            ..login(true)
        }));
    }

    #[test]
    fn a_changed_password_is_offered_over_a_saved_login() {
        assert!(should_offer(Login {
            changed: true,
            ..login(true)
        }));
    }

    #[test]
    fn a_generated_or_changed_password_for_a_new_login_is_offered() {
        assert!(should_offer(Login {
            generated: true,
            ..login(false)
        }));
        assert!(should_offer(Login {
            changed: true,
            ..login(false)
        }));
    }

    /// A misread change form, such as a login with a PIN field, must not
    /// offer the password already saved.
    #[test]
    fn a_change_to_the_same_password_is_not_offered() {
        assert!(!should_offer(Login {
            changed: true,
            differs: Some(false),
            ..login(true)
        }));
    }

    fn record(username: &str) -> wis_storage::CredentialRecord {
        wis_storage::CredentialRecord {
            id: 0,
            host: "example.com".to_string(),
            username: username.to_string(),
            ciphertext: Vec::new(),
            nonce: Vec::new(),
            created_at: chrono::Utc::now(),
            updated_at: chrono::Utc::now(),
        }
    }

    fn target_of(saved: &[&str], username: &str, changed: bool) -> Option<String> {
        let records = saved.iter().map(|u| record(u)).collect();
        target(records, username, changed).map(|r| r.username)
    }

    #[test]
    fn a_login_targets_the_record_saved_under_its_username() {
        assert_eq!(target_of(&["ann", "bob"], "bob", false), Some("bob".into()));
        assert_eq!(target_of(&["ann"], "bob", false), None);
    }

    /// Change forms often hold only password fields, so the username is
    /// missing or read from an unrelated box.
    #[test]
    fn a_change_form_targets_the_only_login_saved_for_the_host() {
        assert_eq!(target_of(&["ann"], "", true), Some("ann".into()));
        assert_eq!(target_of(&["ann", "bob"], "", true), None);
        assert_eq!(target_of(&["ann", "bob"], "bob", true), Some("bob".into()));
        assert_eq!(target_of(&[], "", true), None);
    }

    #[test]
    fn a_login_whose_password_differs_from_the_saved_one_is_offered() {
        assert!(should_offer(Login {
            differs: Some(true),
            ..login(true)
        }));
    }
}
